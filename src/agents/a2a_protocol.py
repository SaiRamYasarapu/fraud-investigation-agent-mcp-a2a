"""
A2A (Agent-to-Agent) protocol layer.


A2A protocol acts as the only communication channel between two agents, the Detection Agent
and the Investigation Agent. So here we are creating an A2A protocol which carries information
between the Investigation Agent and the Detection Agent. In the A2A protocol, each agent needs
an Agent Card, which is like a business card for it — the Agent Card consists of the agent ID,
agent name, and what it is capable of. We also have A2A Task as another class, which is nothing
but the actual message carrier that goes from one agent to another, holding the message in it — it's
like an envelope. And A2A Task Result is the result of the request given by the remote agent. Here,
we call the agent which requested as the client agent, and the agent which responded and gave the
answer to the task, we call the remote agent. So A2A Task Result is the response generated by the
remote agent as a reply to the task being asked.

A2A Server is nothing but where an agent registers itself and makes itself available to be
reached by other agents. And A2A Client is used by an agent to call other agents — it's like
initiating a call. So if an agent needs to be called by someone, it has to register itself
using A2A Server, so it can publish its identity and be reachable by other agents. If an agent
wants to make a call to another agent, it has to use A2A Client to call that other agent.

Right now, it is for local development. Later, I'll be swapping it for HTTP/JSON-RPC — this only touches
A2A Client and A2A Server, not the agents themselves. You can see this in PRODUCTION_SWAP.md.
"""




from __future__ import annotations

import uuid
from collections.abc import Callable
from dataclasses import dataclass
from typing import ClassVar


@dataclass
class AgentCard:
    """Minimal capability manifest: what an agent is called and what
    kinds of tasks it accepts."""

    agent_id: str
    name: str
    skills: list[str]


@dataclass
class A2ATask:
    """A single unit of work passed between agents: who it's from, what's
    being asked, and the payload."""

    task_id: str
    from_agent: str
    to_agent: str
    intent: str
    payload: dict
    status: str = "submitted"


@dataclass
class A2ATaskResult:
    task_id: str
    from_agent: str
    status: str  # "completed" | "failed"
    output: dict


class A2AServer:
    """Registers an agent's handler under its AgentCard so other agents
    can address it by agent_id."""

    _registry: ClassVar[dict[str, A2AServer]] = {}

    def __init__(self, card: AgentCard, handler: Callable[[A2ATask], A2ATaskResult]):
        self.card = card
        self.handler = handler
        A2AServer._registry[card.agent_id] = self

    @classmethod
    def resolve(cls, agent_id: str) -> A2AServer:
        if agent_id not in cls._registry:
            raise ValueError(f"No A2A agent registered with id '{agent_id}'")
        return cls._registry[agent_id]


class A2AClient:
    """Sends a task to another agent by id. In-process here for local
    development; in production this becomes an HTTP/JSON-RPC call to the
    other agent's endpoint."""

    def __init__(self, from_agent_id: str):
        self.from_agent_id = from_agent_id

    def send_task(self, to_agent: str, intent: str, payload: dict) -> A2ATaskResult:
        task = A2ATask(
            task_id=str(uuid.uuid4())[:8],
            from_agent=self.from_agent_id,
            to_agent=to_agent,
            intent=intent,
            payload=payload,
        )
        server = A2AServer.resolve(to_agent)
        return server.handler(task)
